/** Integrate measured atlas boundaries without changing the original illustrations. */
import {readFile,writeFile,access} from 'node:fs/promises';
import {resolve,dirname,basename} from 'node:path';
import {fileURLToPath} from 'node:url';
import assert from 'node:assert/strict';
import {CARDS} from '../catalog.js';
import {validateCardArtManifest} from './validate-card-art.mjs';
const root=resolve(dirname(fileURLToPath(import.meta.url)),'..');
const web=await access(resolve(root,'catalog.js')).then(()=>root,()=>resolve(root,'dist'));
const art=resolve(web,'assets/design-v2/cards/individual');
const manifest=validateCardArtManifest(JSON.parse(await readFile(resolve(art,'manifest.json'),'utf8')),CARDS);
const layouts=JSON.parse(await readFile(resolve(art,'layouts.json'),'utf8'));
const crops={};
for(const card of manifest.cards){
 const layout=layouts.atlases[basename(card.src)];
 delete card.pixelCrop;delete card.sourceSize;
 if(!layout||card.id==='B0512')continue;
 const {width,height,x,y}=layout;
 assert(Number.isInteger(width)&&width>0&&Number.isInteger(height)&&height>0&&Array.isArray(x)&&Array.isArray(y)&&x.every(Number.isInteger)&&y.every(Number.isInteger),'Invalid measured dimensions: '+card.src);
 assert(x.length===5&&y.length===5&&x[0]===0&&y[0]===0&&x[4]===width&&y[4]===height,'Invalid measured atlas: '+card.src);
 assert(x.every((v,i)=>i===0||v>x[i-1])&&y.every((v,i)=>i===0||v>y[i-1]),'Non-increasing boundaries');
 const left=x[card.column],top=y[card.row],cw=x[card.column+1]-left,ch=y[card.row+1]-top;
 const side=Math.floor(Math.min(cw,ch)*(1-2*manifest.atlasSafetyInset));
 const px=Math.round(left+(cw-side)/2),py=Math.round(top+(ch-side)/2);
 assert(px>=left&&py>=top&&px+side<=left+cw&&py+side<=top+ch&&side>0,'Crop crosses a cell');
 card.pixelCrop=[px,py,side,side];card.sourceSize=[width,height];
 crops[card.id]={x:px,y:py,size:side,width,height};
}
validateCardArtManifest(manifest,CARDS);
await writeFile(resolve(art,'manifest.json'),JSON.stringify(manifest,null,2)+'\n');
await writeFile(resolve(web,'card-art-layouts.js'),'/** Measured native artwork crops, generated by scripts/finalize-card-art.mjs. */\nexport const CARD_ART_CROPS = Object.freeze('+JSON.stringify(crops,null,2)+');\n');
console.log(JSON.stringify({cards:manifest.cards.length,measuredAtlasCount:Object.keys(layouts.atlases).length,measuredCrops:Object.keys(crops).length}));
